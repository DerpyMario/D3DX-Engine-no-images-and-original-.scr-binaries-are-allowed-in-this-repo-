#include "scene.h"




//-----------------------------------------------------------------------------
// Name: CScene()
//-----------------------------------------------------------------------------
CScene::CScene()
{
    m_fStartTime = -1.0f;
}




//-----------------------------------------------------------------------------
// Name: ~CScene()
//-----------------------------------------------------------------------------
CScene::~CScene()
{
    FinalCleanup();
}




//-----------------------------------------------------------------------------
// Name: FinalCleanup()
//-----------------------------------------------------------------------------
void CScene::FinalCleanup()
{
    OnLostDevice();
    OnDestroyDevice();
}




//-----------------------------------------------------------------------------
// Name: Go()
//-----------------------------------------------------------------------------
void CScene::Go( FLOAT fTime )
{
    m_fStartTime = fTime;
}




//-----------------------------------------------------------------------------
// Name: OnFrameMove()
// Desc: The camera of a scene is not moved by the parent.
//-----------------------------------------------------------------------------
void CScene::OnFrameMove( FLOAT fTime, FLOAT fElapsedTime, D3DXMATRIX& /*mParent*/ )
{
    m_Camera.OnFrameMove( fTime, fElapsedTime, g_mIdent );
}




//-----------------------------------------------------------------------------
// Name: OnResetDevice()
//-----------------------------------------------------------------------------
HRESULT CScene::OnResetDevice()
{
    m_Camera.CreateProjection();

    return S_OK;
}
